const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1910, height: 936 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('https://fonts.googleapis.com/**', route => route.abort());
    await page.route('https://fonts.gstatic.com/**', route => route.abort());
    await page.goto(pathToFileURL(path.resolve(__dirname, '../index.html')).href);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('[data-open="login"]').click();
    await page.locator('.chip[data-email="docgia@ptit.edu.vn"]').click();
    await page.locator('#loginForm button[type="submit"]').click();
    await page.locator('#appView').waitFor();
    const text = id => page.locator('#' + id).textContent();
    const capture = async name => {
      const filename = path.join(os.tmpdir(), 'ptit-ui-' + name + '.png');
      await page.screenshot({ path: filename, animations: 'disabled' });
      console.log('Screenshot:', filename);
    };
    assert.equal(await text('statBorrowing'), '1');
    assert.equal(await text('statPending'), '0');
    assert.equal(await text('statRemaining'), '2');
    assert.equal(await text('statFines'), '50.000đ');
    assert.equal(await text('libraryName'), 'Nguyễn Hoàng An');
    assert.equal(await page.locator('#popularBooks .book-card').count(), 4);
    await capture('overview');
    await page.locator('[data-nav="search"]').click();
    await page.locator('#bookList .book-card').first().waitFor();
    assert.equal(await page.locator('#bookList .book-card').count(), 8);
    await capture('search');
    await page.locator('[data-filter="Công nghệ"]').click();
    const cats = await page.locator('#bookList .book-cat').allTextContents();
    assert.ok(cats.length && cats.every(category => category === 'Công nghệ'));
    await page.locator('[data-filter="all"]').click();
    const favorite = page.locator('#bookList .favorite-button').first();
    await favorite.click();
    assert.equal(await page.locator('#bookDialog').evaluate(dialog => dialog.open), false);
    await page.locator('[data-filter="favorites"]').click();
    assert.equal(await page.locator('#bookList .book-card').count(), 1);
    await page.reload();
    await page.locator('[data-nav="search"]').click();
    await page.locator('#bookList .book-card').first().waitFor();
    assert.equal(await page.locator('#bookList .favorite-button').first().getAttribute('aria-pressed'), 'true');
    await page.locator('#bookList .book-open').first().click();
    assert.match(await text('bookDetailMeta'), /K2-B1/);
    assert.match(await text('reviewSummary'), /5.0/);
    await capture('detail');
    await page.locator('#writeReviewButton').click();
    assert.equal(await page.locator('#reviewComment').inputValue(), 'Tuổi thơ ùa về, bản in sạch đẹp.');
    await capture('review');
    await page.locator('#reviewStars').selectOption('4');
    await page.locator('#reviewComment').fill('Bản in rõ đẹp, rất đáng đọc.');
    await page.locator('#reviewForm button[type="submit"]').click();
    await page.locator('#reviewDialog').waitFor({ state: 'hidden' });
    assert.match(await text('reviewSummary'), /4.0/);
    assert.match(await text('reviewSummary'), /1 đánh giá/);
    assert.match(await text('reviewList'), /Bản in rõ đẹp/);
    await page.locator('#closeBookDialog').click();
    await page.reload();
    await page.locator('[data-nav="mybooks"]').click();
    await page.locator('#myLoanList tbody tr').first().waitFor();
    assert.equal(await page.locator('#myLoanList tbody tr').count(), 8);
    assert.match(await text('myLoanList'), /13 mục/);
    await capture('mybooks');
    await page.getByRole('navigation', { name: 'Phân trang phiếu mượn' }).getByRole('button', { name: '2', exact: true }).click();
    assert.equal(await page.locator('#myLoanList tbody tr').count(), 5);
    await page.locator('#myLoanList .table-action').first().click();
    assert.equal(await page.locator('#reviewDialog').evaluate(dialog => dialog.open), true);
    await page.locator('#cancelReview').click();
    await page.locator('#notificationsButton').click();
    assert.match(await text('utilityContent'), /Hạn trả/);
    await page.locator('#closeUtility').click();
    await page.locator('#profileButton').click();
    assert.match(await text('utilityContent'), /B22DCCN101/);
    await page.keyboard.press('Escape');
    await page.locator('#themeButton').click();
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    await capture('dark');
    await page.locator('#themeButton').click();
    await page.setViewportSize({ width: 390, height: 844 });
    await capture('mobile-overview');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('#menuToggle').click();
    await page.locator('[data-nav="search"]').click();
    await page.locator('#bookList .book-card').first().waitFor();
    await capture('mobile-search');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('#bookList .book-open').first().click();
    await capture('mobile-detail');
    await page.locator('#writeReviewButton').click();
    await capture('mobile-review');
    const box = await page.locator('#reviewDialog').boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 844);
    assert.deepEqual(errors, []);
    console.log('PASS thống kê, thẻ thư viện, bộ lọc, yêu thích, cập nhật đánh giá, bảng phân trang, thông báo, hồ sơ, theme, responsive');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
